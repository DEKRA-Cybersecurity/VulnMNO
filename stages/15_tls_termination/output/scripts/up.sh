#!/usr/bin/env bash
#
# VulnMNO lab launcher — makes TLS work on ANY network with zero edits.
#
# The only value that changes when you move networks is this host's LAN IP.
# This script detects it, writes docker/.env so Caddy issues a cert for it
# (and serves it to no-SNI clients like a browser hitting an IP literal),
# then brings up the stack with the TLS profile.
#
# Usage:
#   bash src/scripts/up.sh            # auto-detect LAN IP + build + up -d
#   bash src/scripts/up.sh <ip>       # force this IP (detection guessed wrong,
#                                      #   VPN up, macOS/WSL2, etc.)
#   bash src/scripts/up.sh down       # stop the stack
#
# Re-run after changing networks (new Wi-Fi, VPN on/off, etc). Same-machine
# access (https://localhost) and the Android emulator (https://10.0.2.2)
# work even with no detected IP — those addresses never change.
#
# Auto-detection is Linux-native (uses `ip`). On macOS / WSL2, or if it
# guesses wrong, pass the IP explicitly: `up.sh 192.168.1.50`.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOCKER_DIR="$(cd "$SCRIPT_DIR/../docker" && pwd)"
ENV_FILE="$DOCKER_DIR/.env"
COMPOSE=(docker compose -f "$DOCKER_DIR/docker-compose.yml" --env-file "$ENV_FILE")

# `down` shortcut: tear the stack down (still needs an env file to exist).
if [ "${1:-}" = "down" ]; then
    [ -f "$ENV_FILE" ] || printf 'VULNMNO_TLS_HOSTS=localhost\nVULNMNO_DEFAULT_SNI=localhost\n' > "$ENV_FILE"
    exec "${COMPOSE[@]}" --profile tls down
fi

# Any other first arg is an explicit IP/host override — skip detection.
OVERRIDE="${1:-}"

# Interface the default route leaves by, and its source address.
default_route_dev() {
    ip route get 1.1.1.1 2>/dev/null \
        | awk '{for (i = 1; i <= NF; i++) if ($i == "dev") { print $(i + 1); exit }}'
}
default_route_src() {
    ip route get 1.1.1.1 2>/dev/null \
        | awk '{for (i = 1; i <= NF; i++) if ($i == "src") { print $(i + 1); exit }}'
}

# Real LAN IPs (multi-homed: Wi-Fi + Ethernet), excluding loopback and every
# docker/virtual/VPN interface by name prefix. These widen the cert SAN list
# and, when the default route is a VPN, supply the physical IP to fall back on.
extra_ips() {
    ip -4 -o addr show scope global 2>/dev/null \
        | awk '$2 !~ /^(docker0|br-|veth|virbr|lo|tun|tap|wg|ppp)/ { split($4, a, "/"); print a[1] }'
}

if [ -n "$OVERRIDE" ]; then
    PRIMARY="$OVERRIDE"
    echo "Using IP override: $PRIMARY"
else
    DEV="$(default_route_dev || true)"
    case "$DEV" in
        tun*|tap*|wg*|ppp*)
            # Default route is a VPN tunnel — its src is the VPN IP, but the
            # lab is reached by the *physical* LAN IP. Prefer that for the
            # no-SNI default cert, so a browser at the LAN IP gets a match.
            PRIMARY="$(extra_ips | head -n1 || true)"
            if [ -n "$PRIMARY" ]; then
                echo "NOTE: default route is a VPN ($DEV); using physical LAN IP $PRIMARY for the cert." >&2
                echo "      Wrong guess? pass it explicitly:  bash $0 <ip>"          >&2
            fi
            ;;
        *)
            PRIMARY="$(default_route_src || true)"
            ;;
    esac
fi

if [ -n "$PRIMARY" ]; then
    DEFAULT_SNI="$PRIMARY"
else
    # No usable IP (air-gapped, or non-Linux without an override).
    DEFAULT_SNI="localhost"
    echo "WARN: could not detect a LAN IP — falling back to localhost." >&2
    echo "      Same-machine and emulator access work; for a physical phone"   >&2
    echo "      or LAN peer, pass your IP:  bash $0 <ip>"                       >&2
fi

# nip.io alias of the primary IP (e.g. 192.168.1.50.nip.io -> 192.168.1.50).
# Lets Burp / MITM proxies intercept the app's HTTPS by *hostname*: OkHttp
# rejects Burp's DNS-type SAN when the target is a bare IP literal (it wants
# an iPAddress SAN), but accepts it for a hostname. Point the app's backend
# override at this name while proxying. Only meaningful for an IPv4 primary.
NIP=""
if printf '%s' "$PRIMARY" | grep -qE '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$'; then
    NIP="${PRIMARY}.nip.io"
fi

# Dedupe, keep order: detected/forced IP first, its nip.io alias, then physical
# LAN IPs, then the constant fallbacks. A leading empty field (PRIMARY unset)
# is dropped by the NF filter.
HOSTS="$(printf '%s\n' "$PRIMARY" "$NIP" $(extra_ips) 10.0.2.2 localhost 127.0.0.1 \
    | awk 'NF && !seen[$0]++' | tr '\n' ' ' | sed 's/ *$//')"

cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/up.sh on each run — DO NOT COMMIT (gitignored).
# Holds this host's detected LAN IP so Caddy can serve TLS on this network.
VULNMNO_TLS_HOSTS=$HOSTS
VULNMNO_DEFAULT_SNI=$DEFAULT_SNI
EOF

echo "Detected LAN IP : ${PRIMARY:-<none — localhost only>}"
echo "TLS host list   : $HOSTS"
echo "Default SNI cert: $DEFAULT_SNI"
echo "Wrote           : $ENV_FILE"
echo

"${COMPOSE[@]}" --profile tls up -d --build

ADDR="${PRIMARY:-localhost}"
echo
echo "Admin portal : https://$ADDR/admin/login   (ops / admin1234)"
echo "API (HTTP)   : http://$ADDR:8000/api/"
echo "Trust the CA : bash $SCRIPT_DIR/install_caddy_ca.sh"
echo "  (browsers warn until the Caddy local CA is imported — see README)"
[ -n "$NIP" ] && echo "MITM (Burp)  : set the app backend override to  $NIP  (hostname, so OkHttp accepts Burp's cert)"
